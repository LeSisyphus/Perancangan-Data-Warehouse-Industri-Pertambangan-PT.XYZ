SET NOCOUNT ON;
SELECT 'INSERT #expected VALUES (' + QUOTENAME(TABLE_SCHEMA,'''') + ',' + QUOTENAME(TABLE_NAME,'''') + ',' + QUOTENAME(COLUMN_NAME,'''') + ',' + QUOTENAME(DATA_TYPE,'''') + ','
  + ISNULL(CAST(CHARACTER_MAXIMUM_LENGTH AS varchar(10)),'NULL') + ',' + ISNULL(CAST(NUMERIC_PRECISION AS varchar(10)),'NULL') + ',' + ISNULL(CAST(NUMERIC_SCALE AS varchar(10)),'NULL') + ');'
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA IN ('dim','fact')
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;